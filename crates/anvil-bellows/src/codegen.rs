//! Emit `routes.module.ts` from parsed controller metadata.
//!
//! Follows the same strategy as `anvil-codegen`: build the TypeScript source as
//! a [`String`], validate it by parsing with Oxc, then re-emit with
//! `oxc_codegen::Codegen` for canonical formatting. The banner is prepended as
//! raw text (Codegen strips comments).

use std::fmt::Write as _;
use std::path::{Component, Path, PathBuf};

use oxc_allocator::Allocator;
use oxc_codegen::Codegen;
use oxc_parser::Parser;
use oxc_span::SourceType;
use thiserror::Error;

use crate::parser::{ControllerFile, CtorParam, ParamKind, ReturnKind, Route};

/// Banner prepended to every generated file.
pub const BANNER: &str = "// AUTO-GENERATED by anvil-bellows. Do not edit.\n";

/// All ways code emission can fail.
#[derive(Debug, Error)]
pub enum EmitError {
    /// The string-built TS failed to parse — this is a codegen bug.
    #[error("emitter produced unparseable TypeScript: {errors:?}")]
    EmittedSyntaxError {
        /// Oxc parser error messages.
        errors: Vec<String>,
    },
}

/// Emit a `routes.module.ts` file.
///
/// `output_path` is where the file will be written; it is used to compute
/// relative import specifiers. `controller_files` is the parsed metadata from
/// [`crate::parser::parse_entry`].
///
/// # Errors
///
/// Returns [`EmitError`] if the generated TypeScript fails Oxc's parser (a
/// codegen invariant — should never happen with valid input).
pub fn emit_routes_module(
    controller_files: &[ControllerFile],
    output_path: &Path,
    version: &str,
) -> Result<String, EmitError> {
    let out_dir = output_path
        .parent()
        .unwrap_or_else(|| Path::new("."));

    let body = build_ts(controller_files, out_dir);

    let allocator = Allocator::default();
    let ret = Parser::new(&allocator, &body, SourceType::ts()).parse();
    if !ret.errors.is_empty() {
        return Err(EmitError::EmittedSyntaxError {
            errors: ret.errors.iter().map(|e| format!("{e:?}")).collect(),
        });
    }
    let canonical = Codegen::new().build(&ret.program).code;

    let mut output = String::new();
    writeln!(output, "// AUTO-GENERATED by anvil-bellows v{version}. Do not edit.")
        .expect("write to String");
    output.push_str(&canonical);
    Ok(output)
}

/// Build the raw TypeScript source string (before oxc canonicalization).
fn build_ts(files: &[ControllerFile], out_dir: &Path) -> String {
    let mut s = String::new();

    let any_ctor_params = files
        .iter()
        .flat_map(|f| &f.controllers)
        .any(|c| !c.ctor_params.is_empty());
    let anvil_imports = if any_ctor_params {
        "Module, Provides, Singleton, IntoSet"
    } else {
        "Module, Provides, IntoSet"
    };
    writeln!(s, "import {{ {anvil_imports} }} from \"@msulak/anvil\";").unwrap();
    s.push_str("import type { RouteDefinition } from \"@msulak/anvil-bellows\";\n");

    // One import per controller file — includes controller class + any schema refs.
    // Also collect dep types that need separate imports.
    for file in files {
        let specifier = import_specifier(out_dir, &file.source_path);
        // Collect all identifiers to import from this file.
        let mut imports: Vec<String> = Vec::new();
        for ctrl in &file.controllers {
            imports.push(ctrl.class_name.clone());
            for route in &ctrl.routes {
                collect_schema_refs(route, &mut imports);
            }
        }
        imports.dedup();
        writeln!(s, "import {{ {} }} from \"{specifier}\";", imports.join(", ")).unwrap();
    }

    // Emit imports for controller dep types that come from other files.
    // Group by resolved absolute source path so we emit one import per file.
    let mut dep_imports: std::collections::BTreeMap<String, Vec<String>> =
        std::collections::BTreeMap::new();
    for file in files {
        let ctrl_spec = import_specifier(out_dir, &file.source_path);
        for ctrl in &file.controllers {
            for cp in &ctrl.ctor_params {
                let Some(abs) = &cp.abs_source else { continue };
                let spec = import_specifier(out_dir, abs);
                // Skip if the dep type is already imported from the controller file.
                if spec == ctrl_spec {
                    continue;
                }
                dep_imports
                    .entry(spec)
                    .or_default()
                    .push(cp.type_name.clone());
            }
        }
    }
    for (spec, mut names) in dep_imports {
        names.sort();
        names.dedup();
        writeln!(s, "import type {{ {} }} from \"{spec}\";", names.join(", ")).unwrap();
    }

    s.push('\n');
    s.push_str("@Module\n");
    s.push_str("export class RoutesModule {\n");

    for file in files {
        for ctrl in &file.controllers {
            // Emit a @Singleton @Provides binding for the controller itself,
            // taking its constructor deps as DI parameters.
            if !ctrl.ctor_params.is_empty() {
                emit_controller_provider(&mut s, ctrl.class_name.as_str(), &ctrl.ctor_params);
            }

            for route in &ctrl.routes {
                let method_name = provider_method_name(
                    &ctrl.class_name,
                    route.method.decorator_name(),
                    &route.handler_name,
                );
                let param_name = lower_first(&ctrl.class_name);
                let class_name = &ctrl.class_name;
                let http_verb = route.method.http_verb();
                let path = &route.path;

                let handler_body = emit_handler(&param_name, &route.handler_name, route);

                writeln!(
                    s,
                    "  @IntoSet @Provides\n  static {method_name}({param_name}: {class_name}): RouteDefinition {{\n    return {{\n      method: \"{http_verb}\",\n      path: \"{path}\",\n      handler: {handler_body},\n    }};\n  }}"
                )
                .unwrap();
            }
        }
    }

    s.push_str("}\n");
    s
}

/// Emit a `@Singleton @Provides` method that constructs a controller from its deps.
fn emit_controller_provider(s: &mut String, class_name: &str, ctor_params: &[CtorParam]) {
    let method_name = lower_first(class_name);
    let params_sig = ctor_params
        .iter()
        .map(|p| format!("{}: {}", p.name, p.type_name))
        .collect::<Vec<_>>()
        .join(", ");
    let ctor_args = ctor_params
        .iter()
        .map(|p| p.name.as_str())
        .collect::<Vec<_>>()
        .join(", ");
    writeln!(
        s,
        "  @Singleton @Provides\n  static {method_name}({params_sig}): {class_name} {{\n    return new {class_name}({ctor_args});\n  }}"
    )
    .unwrap();
}

/// Collect schema identifiers from a route's params and return kind into `out`.
fn collect_schema_refs(route: &Route, out: &mut Vec<String>) {
    for param in &route.params {
        let ident = match &param.kind {
            ParamKind::Body(s) | ParamKind::Query(s) | ParamKind::Params(s) => &s.ident,
            _ => continue,
        };
        if !out.contains(ident) {
            out.push(ident.clone());
        }
    }
    if let ReturnKind::Responds { schema, .. } = &route.return_kind {
        if !out.contains(&schema.ident) {
            out.push(schema.ident.clone());
        }
    }
}

/// Returns true when all params are recognized types (no `Unknown`).
fn all_params_recognized(route: &Route) -> bool {
    route
        .params
        .iter()
        .all(|p| !matches!(p.kind, ParamKind::Unknown))
}

/// Emit the handler expression for a route.
///
/// - All Unknown params → v0.1 passthrough: `(req, res) => ctrl.method(req, res)`
/// - All recognized params → typed adapter with validation
fn emit_handler(ctrl_param: &str, handler: &str, route: &Route) -> String {
    // If no params at all, or any param is Unknown, use v0.1 passthrough.
    if route.params.is_empty() || !all_params_recognized(route) {
        return format!("(req, res) => {ctrl_param}.{handler}(req, res)");
    }

    let is_async = matches!(
        route.return_kind,
        ReturnKind::Responds { is_async: true, .. } | ReturnKind::Void { is_async: true }
    );
    let async_kw = if is_async { "async " } else { "" };

    let mut body = String::new();

    // Schema validation prologue — one block per schema param.
    let mut call_args: Vec<String> = Vec::new();
    for param in &route.params {
        match &param.kind {
            ParamKind::Body(schema) => {
                let s = &schema.ident;
                let n = &param.name;
                writeln!(body, "      const _{n} = {s}.safeParse(req.body);").unwrap();
                writeln!(body, "      if (!_{n}.success) {{ res.status(400).json(_{n}.error); return; }}").unwrap();
                call_args.push(format!("_{n}.data"));
            }
            ParamKind::Query(schema) => {
                let s = &schema.ident;
                let n = &param.name;
                writeln!(body, "      const _{n} = {s}.safeParse(req.query);").unwrap();
                writeln!(body, "      if (!_{n}.success) {{ res.status(400).json(_{n}.error); return; }}").unwrap();
                call_args.push(format!("_{n}.data"));
            }
            ParamKind::Params(schema) => {
                let s = &schema.ident;
                let n = &param.name;
                writeln!(body, "      const _{n} = {s}.safeParse(req.params);").unwrap();
                writeln!(body, "      if (!_{n}.success) {{ res.status(400).json(_{n}.error); return; }}").unwrap();
                call_args.push(format!("_{n}.data"));
            }
            ParamKind::Request => call_args.push("req".to_owned()),
            ParamKind::Response => call_args.push("res".to_owned()),
            ParamKind::Unknown => unreachable!("filtered above"),
        }
    }

    let args = call_args.join(", ");
    let await_kw = if is_async { "await " } else { "" };

    match &route.return_kind {
        ReturnKind::Responds { schema, .. } => {
            let s = &schema.ident;
            writeln!(body, "      const _result = {await_kw}{ctrl_param}.{handler}({args});").unwrap();
            writeln!(body, "      const _validated = {s}.safeParse(_result);").unwrap();
            writeln!(body, "      if (!_validated.success) {{ res.status(500).json(_validated.error); return; }}").unwrap();
            body.push_str("      res.json(_validated.data);");
        }
        ReturnKind::Void { .. } => {
            // Controller manages `res` itself.
            write!(body, "      {await_kw}{ctrl_param}.{handler}({args});").unwrap();
        }
    }

    // Trim trailing newline from body so oxc_codegen formats cleanly.
    let body = body.trim_end();

    format!("{async_kw}(req, res) => {{\n{body}\n    }}")
}

/// Generate the provider static method name from controller class, decorator, and handler.
///
/// `UserController` + `Get` + `byId` → `userControllerGetById`
fn provider_method_name(class_name: &str, decorator: &str, handler: &str) -> String {
    format!(
        "{}{}{}",
        lower_first(class_name),
        decorator,
        upper_first(handler)
    )
}

/// Lower-case the first character of a string.
fn lower_first(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_lowercase().to_string() + chars.as_str(),
    }
}

/// Upper-case the first character of a string.
fn upper_first(s: &str) -> String {
    let mut chars = s.chars();
    match chars.next() {
        None => String::new(),
        Some(c) => c.to_uppercase().to_string() + chars.as_str(),
    }
}

/// Compute a `./`-prefixed relative import specifier from `out_dir` to `source_path`,
/// stripping the `.ts` extension.
fn import_specifier(out_dir: &Path, source_path: &Path) -> String {
    let without_ext = strip_ts_extension(source_path);
    let rel = relative_path(out_dir, &without_ext)
        .unwrap_or_else(|| without_ext.clone());
    let raw = rel.to_string_lossy().replace('\\', "/");
    if raw.starts_with("./") || raw.starts_with("../") {
        raw
    } else {
        format!("./{raw}")
    }
}

/// Strip `.ts`, `.tsx`, or `.d.ts` from a path.
fn strip_ts_extension(path: &Path) -> PathBuf {
    let s = path.to_string_lossy();
    for suffix in [".d.ts", ".tsx", ".ts"] {
        if let Some(stripped) = s.strip_suffix(suffix) {
            return PathBuf::from(stripped);
        }
    }
    path.to_path_buf()
}

/// Compute a relative path from `from` (a directory) to `to` (a file path),
/// both expected to be absolute or consistently relative.
fn relative_path(from: &Path, to: &Path) -> Option<PathBuf> {
    let from_comps: Vec<Component<'_>> = from.components().collect();
    let to_comps: Vec<Component<'_>> = to.components().collect();
    let mut i = 0;
    while i < from_comps.len() && i < to_comps.len() && from_comps[i] == to_comps[i] {
        i += 1;
    }
    let mut rel = PathBuf::new();
    for _ in &from_comps[i..] {
        rel.push("..");
    }
    for comp in &to_comps[i..] {
        rel.push(comp);
    }
    if rel.as_os_str().is_empty() {
        None
    } else {
        Some(rel)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parser::{Controller, HttpMethod, ReturnKind, Route, TypedParam};

    fn make_file(path: &str, class: &str, routes: Vec<(&str, HttpMethod, &str)>) -> ControllerFile {
        ControllerFile {
            source_path: PathBuf::from(path),
            controllers: vec![Controller {
                class_name: class.to_owned(),
                ctor_params: vec![],
                tags: vec![],
                security: vec![],
                routes: routes
                    .into_iter()
                    .map(|(p, m, h)| Route {
                        method: m,
                        path: p.to_owned(),
                        handler_name: h.to_owned(),
                        params: vec![],
                        return_kind: ReturnKind::Void { is_async: false },
                        deprecated: false,
                        extra_responses: vec![],
                    })
                    .collect(),
            }],
        }
    }

    fn make_typed_file(
        path: &str,
        class: &str,
        routes: Vec<(&str, HttpMethod, &str, Vec<TypedParam>, ReturnKind)>,
    ) -> ControllerFile {
        ControllerFile {
            source_path: PathBuf::from(path),
            controllers: vec![Controller {
                class_name: class.to_owned(),
                ctor_params: vec![],
                tags: vec![],
                security: vec![],
                routes: routes
                    .into_iter()
                    .map(|(p, m, h, params, return_kind)| Route {
                        method: m,
                        path: p.to_owned(),
                        handler_name: h.to_owned(),
                        params,
                        return_kind,
                        deprecated: false,
                        extra_responses: vec![],
                    })
                    .collect(),
            }],
        }
    }

    #[test]
    fn provider_method_name_cases() {
        assert_eq!(
            provider_method_name("UserController", "Get", "byId"),
            "userControllerGetById"
        );
        assert_eq!(
            provider_method_name("PostController", "Post", "create"),
            "postControllerPostCreate"
        );
        assert_eq!(
            provider_method_name("HealthController", "Get", "ping"),
            "healthControllerGetPing"
        );
    }

    #[test]
    fn emit_single_controller() {
        let files = vec![make_file(
            "/project/src/user-controller.ts",
            "UserController",
            vec![
                ("/users/:id", HttpMethod::Get, "byId"),
                ("/users", HttpMethod::Post, "create"),
            ],
        )];
        let output_path = Path::new("/project/src/routes.module.ts");
        let result = emit_routes_module(&files, output_path, "0.0.1").unwrap();
        assert!(result.contains("@Module"));
        assert!(result.contains("RoutesModule"));
        assert!(result.contains("userControllerGetById"));
        assert!(result.contains("userControllerPostCreate"));
        assert!(result.contains("\"GET\""));
        assert!(result.contains("\"/users/:id\""));
        assert!(result.contains("import { UserController }"));
        assert!(result.contains("\"./user-controller\""));
    }

    #[test]
    fn emit_multiple_controllers() {
        let files = vec![
            make_file(
                "/project/src/post-controller.ts",
                "PostController",
                vec![("/posts", HttpMethod::Get, "list")],
            ),
            make_file(
                "/project/src/user-controller.ts",
                "UserController",
                vec![("/users", HttpMethod::Get, "list")],
            ),
        ];
        let output_path = Path::new("/project/src/routes.module.ts");
        let result = emit_routes_module(&files, output_path, "0.0.1").unwrap();
        assert!(result.contains("PostController"));
        assert!(result.contains("UserController"));
        assert!(result.contains("postControllerGetList"));
        assert!(result.contains("userControllerGetList"));
    }

    #[test]
    fn emit_typed_adapter_body_and_responds() {
        use crate::parser::{ParamKind, SchemaRef};

        let params = vec![
            TypedParam { name: "body".into(), kind: ParamKind::Body(SchemaRef { ident: "CreateBody".into() }) },
            TypedParam { name: "req".into(), kind: ParamKind::Request },
        ];
        let return_kind = ReturnKind::Responds {
            schema: SchemaRef { ident: "UserSchema".into() },
            is_async: false,
        };

        let files = vec![make_typed_file(
            "/project/src/user-controller.ts",
            "UserController",
            vec![("/users", HttpMethod::Post, "create", params, return_kind)],
        )];
        let output_path = Path::new("/project/src/routes.module.ts");
        let result = emit_routes_module(&files, output_path, "0.0.1").unwrap();

        // Schema imports alongside the controller.
        assert!(result.contains("UserController, CreateBody, UserSchema"));
        // safeParse calls.
        assert!(result.contains("CreateBody.safeParse(req.body)"));
        assert!(result.contains("UserSchema.safeParse(_result)"));
        // Error responses.
        assert!(result.contains("res.status(400)"));
        assert!(result.contains("res.status(500)"));
        // Success response.
        assert!(result.contains("res.json(_validated.data)"));
        // No typeof in generated code.
        assert!(!result.contains("typeof CreateBody"));
    }

    #[test]
    fn unknown_params_fallback_to_passthrough() {
        use crate::parser::ParamKind;

        let params = vec![
            TypedParam { name: "req".into(), kind: ParamKind::Unknown },
            TypedParam { name: "res".into(), kind: ParamKind::Unknown },
        ];
        let files = vec![make_typed_file(
            "/project/src/user-controller.ts",
            "UserController",
            vec![("/users", HttpMethod::Get, "list", params, ReturnKind::Void { is_async: false })],
        )];
        let output_path = Path::new("/project/src/routes.module.ts");
        let result = emit_routes_module(&files, output_path, "0.0.1").unwrap();

        // v0.1 passthrough shape.
        assert!(result.contains("(req, res) => userController.list(req, res)"));
        // No safeParse.
        assert!(!result.contains("safeParse"));
    }
}
